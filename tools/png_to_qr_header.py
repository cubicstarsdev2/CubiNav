#!/usr/bin/env python3
"""Make a QR code PNG for a URL and/or convert a QR PNG into the qr_app.h format
(one uint32_t per row).

Usage:
    # Generate the QR PNG from a URL, then convert it to the header:
    python png_to_qr_header.py --url https://cubinav.app/get -o qr_app.h

    # Convert an existing PNG (the URL only fills in QR_APP_URL):
    python png_to_qr_header.py qr.png -o qr_app.h --url https://cubinav.app/get

Requires Pillow (pip install pillow), plus segno (pip install segno) when
generating the PNG from a URL.

The row format matches the original header: row y, module x is dark when
bit (N-1-x) of ROWS[y] is set. Rows are uint32_t for N <= 32 (QR versions
1-3: 21, 25, 29 modules) and automatically uint64_t (with ULL literals) for
larger codes, up to N = 64.
"""
import argparse
import sys
from PIL import Image


def generate_png(url, path, ecc="M", version=None, scale=10, border=4):
    """Render a QR code for `url` to a PNG using segno."""
    try:
        import segno
    except ImportError:
        sys.exit("Generating a QR needs segno: pip install segno "
                 "(or pass an existing PNG instead).")
    qr = segno.make(url, error=ecc.lower(), version=version, micro=False)
    qr.save(path, kind="png", scale=scale, border=border)
    return qr


def load_modules(path, n_override=None, threshold=128, invert=False):
    img = Image.open(path)
    # Flatten transparency onto white so transparent backgrounds read as light.
    if img.mode in ("RGBA", "LA", "P"):
        img = img.convert("RGBA")
        bg = Image.new("RGBA", img.size, (255, 255, 255, 255))
        img = Image.alpha_composite(bg, img)
    img = img.convert("L")
    if invert:
        img = img.point(lambda v: 255 - v)
    w, h = img.size
    px = img.load()

    def dark(x, y):
        return px[x, y] < threshold

    # Bounding box of dark pixels (this strips the quiet zone).
    xs, ys = [], []
    for y in range(h):
        for x in range(w):
            if dark(x, y):
                xs.append(x)
                ys.append(y)
    if not xs:
        sys.exit("No dark pixels found. Is the image inverted? Try --invert.")
    x0, x1 = min(xs), max(xs)
    y0, y1 = min(ys), max(ys)
    size = max(x1 - x0, y1 - y0) + 1

    if n_override:
        n = n_override
        mod = size / n
    else:
        # The top row of the top-left finder pattern is 7 dark modules wide.
        run = 0
        x = x0
        while x <= x1 and dark(x, y0):
            run += 1
            x += 1
        mod = run / 7.0
        n = round(size / mod)
        if (n - 17) % 4 != 0 or n < 21:
            sys.exit(
                f"Detected {n} modules, which is not a valid QR size "
                f"(21, 25, 29, ...). Crop the image tightly or pass --n."
            )
        mod = size / n  # refine

    grid = []
    for r in range(n):
        row = []
        cy = int(y0 + (r + 0.5) * mod)
        for c in range(n):
            cx = int(x0 + (c + 0.5) * mod)
            row.append(dark(min(cx, w - 1), min(cy, h - 1)))
        grid.append(row)
    return grid


def write_header(grid, out, url, ecc, name):
    n = len(grid)
    if n > 64:
        sys.exit(f"{n} modules won't fit in uint64_t rows (max 64).")
    wide = n > 32  # QR version 4+ needs 64-bit rows
    ctype = "uint64_t" if wide else "uint32_t"
    suffix = "ULL" if wide else ""
    version = (n - 17) // 4
    digits = (n + 3) // 4
    lines = [
        "#pragma once",
        "// QR code shown on the setup screen: opens the app's download page.",
        f"// Generated by png_to_qr_header.py: version {version}, "
        f"error correction {ecc}, {n} x {n} modules.",
        "// If you change the QR size, update QR_APP_N and the sprite size in ui.cpp.",
        "#include <stdint.h>",
    ]
    if url:
        lines.append(f'#define {name}_URL  "{url}"')
    lines.append(f"#define {name}_N    {n}")
    lines.append(f"// Row y, module x is dark when bit ({n - 1} - x) of {name}_ROWS[y] is set.")
    if wide:
        lines.append(f"// NOTE: rows are {ctype} (QR is wider than 32 modules): read them as 64-bit,")
        lines.append("// e.g. (row >> (N - 1 - x)) & 1 with row declared uint64_t.")
    lines.append(f"static const {ctype} {name}_ROWS[{name}_N] = {{")
    for row in grid:
        v = 0
        for c in row:
            v = (v << 1) | int(c)
        art = "".join("#" if c else "." for c in row)
        lines.append(f"  0x{v:0{digits}X}{suffix},  // {art}")
    lines.append("};")
    text = "\n".join(lines) + "\n"
    if out == "-":
        sys.stdout.write(text)
    else:
        with open(out, "w", newline="\n") as f:
            f.write(text)


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("png", nargs="?",
                    help="input QR code image (omit to generate one from --url)")
    ap.add_argument("-o", "--out", default="qr_app.h", help="output header ('-' for stdout)")
    ap.add_argument("--url", help="URL to encode when generating; also written as QR_APP_URL")
    ap.add_argument("--png-out", default="qr_app.png",
                    help="where to save the generated PNG (default qr_app.png)")
    ap.add_argument("--ecc", default="M",
                    help="error correction L/M/Q/H: used when generating, and noted in the header comment")
    ap.add_argument("--qr-version", type=int,
                    help="force QR version 1-3 when generating (default: smallest that fits)")
    ap.add_argument("--name", default="QR_APP", help="macro/array prefix (default QR_APP)")
    ap.add_argument("--n", type=int, help="force module count instead of auto-detecting")
    ap.add_argument("--invert", action="store_true", help="light-on-dark QR image")
    args = ap.parse_args()

    png = args.png
    if png is None:
        if not args.url:
            ap.error("give a PNG to convert, or --url to generate one")
        generate_png(args.url, args.png_out, args.ecc, args.qr_version)
        png = args.png_out
        print(f"Wrote {png}")

    grid = load_modules(png, args.n, 128, args.invert)
    write_header(grid, args.out, args.url, args.ecc, args.name)
    if args.out != "-":
        print(f"Wrote {args.out} ({len(grid)}x{len(grid)} modules)")


if __name__ == "__main__":
    main()