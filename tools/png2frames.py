#!/usr/bin/env python3
"""
png2frames.py - convert PNG frames into a C header of 1-bpp frames for the TahVia boot animation.

  python png2frames.py frames/            ->  boot_frames.h

Each pixel becomes one bit: 1 = black, 0 = white (a pixel darker than --threshold is black; transparent counts as
white). Frame size is taken from the first PNG. Optional: -o FILE, --fps N, --size N, --threshold N (default 128),
--invert (swap black/white), --preview (ASCII of frame 0).

Output layout matches MonoTileRenderer: row-major, MSB first, SIZE/8 bytes per row.

--format alpha4  stores 4-bit darkness (alpha, and darker colours, count as darker) run-length encoded instead of
1 bpp, one byte per run [level:4 | length-1:4]. The firmware (boot_alpha.h) upscales it and dithers it at the
output resolution. Use it for soft / antialiased art; pair it with --size of the SOURCE frame (not upscaled).
The default (--format bits) is unchanged.
Requires: pip install pillow
"""
import argparse, os, re, sys
from PIL import Image


def natural_key(s):
    return [int(t) if t.isdigit() else t.lower() for t in re.split(r'(\d+)', s)]


def collect(paths):
    files = []
    for p in paths:
        if os.path.isdir(p):
            files += [os.path.join(p, f) for f in sorted(os.listdir(p), key=natural_key)
                      if f.lower().endswith('.png')]
        else:
            files.append(p)
    return files


def to_bits(path, size, thr, invert):
    """One bit per pixel: 1 = black, 0 = white. Transparent pixels count as white."""
    im = Image.open(path).convert('RGBA')
    if im.size != (size, size):
        print(f'warning: {path} is {im.size[0]}x{im.size[1]}, resizing to {size}x{size} (nearest)', file=sys.stderr)
        im = im.resize((size, size), Image.NEAREST)
    bg = Image.new('RGBA', im.size, (255, 255, 255, 255))
    px = Image.alpha_composite(bg, im).convert('L').load()
    return [[(px[x, y] < thr) != invert for x in range(size)] for y in range(size)]


def to_levels(path, size, invert):
    """4-bit darkness per pixel (0 = white/transparent .. 15 = black), composited over white."""
    im = Image.open(path).convert('RGBA')
    if im.size != (size, size):
        print(f'warning: {path} is {im.size[0]}x{im.size[1]}, resizing to {size}x{size} (nearest)', file=sys.stderr)
        im = im.resize((size, size), Image.NEAREST)
    bg = Image.new('RGBA', im.size, (255, 255, 255, 255))
    px = Image.alpha_composite(bg, im).convert('L').load()
    out = []
    for y in range(size):
        for x in range(size):
            d = px[x, y] if invert else 255 - px[x, y]
            out.append((d * 15 + 127) // 255)
    return out


def rle4(levels):
    """[level:4 | len-1:4] runs over the whole frame, row-major (runs may cross rows)."""
    out = bytearray()
    i, n = 0, len(levels)
    while i < n:
        v, j = levels[i], i + 1
        while j < n and levels[j] == v and j - i < 16:
            j += 1
        out.append((v << 4) | (j - i - 1))
        i = j
    return out


def pack(rows):
    out = bytearray()
    for row in rows:
        for i in range(0, len(row), 8):
            v = 0
            for k in range(8):
                if row[i + k]:
                    v |= 0x80 >> k
            out.append(v)
    return out


def write_alpha4(a, files):
    frames = [rle4(to_levels(f, a.size, a.invert)) for f in files]
    mean = sum(sum((b >> 4) * ((b & 15) + 1) for b in f) for f in frames) / (15.0 * a.size * a.size * len(frames))
    if mean > 0.97 or mean < 0.003:
        print(f'warning: mean darkness is {mean:.0%} - the frames are probably all-black or all-white; check --invert', file=sys.stderr)

    if a.preview:
        shades = ' .:-=+*#%@'
        lv = []
        for b in frames[0]:
            lv += [b >> 4] * ((b & 15) + 1)
        for y in range(a.size):
            print(''.join(shades[min(9, lv[y * a.size + x] * 10 // 16)] for x in range(a.size)))

    offs, o = [], 0
    for f in frames:
        offs.append(o); o += len(f)
    offs.append(o)

    with open(a.out, 'w') as h:
        h.write('// Generated by png2frames.py --format alpha4 - do not edit.\n')
        h.write('// 4-bit darkness, run-length encoded: one byte per run [level:4 | length-1:4], row-major per frame.\n')
        h.write('// Decoded and dithered by boot_alpha.h.\n')
        h.write('#pragma once\n#include <stdint.h>\n#include <pgmspace.h>\n\n')
        h.write(f'#define BOOT_FRAME_FORMAT 1\n#define BOOT_FRAME_W     {a.size}\n#define BOOT_FRAME_H     {a.size}\n')
        h.write(f'#define BOOT_FRAME_COUNT {len(frames)}\n#define BOOT_FRAME_FPS   {a.fps}\n')
        h.write(f'#ifndef BOOT_DITHER_SIZE\n#define BOOT_DITHER_SIZE {a.dither}   // Bayer matrix side, power of two 2..256 (override with -DBOOT_DITHER_SIZE=N)\n#endif\n')
        h.write(f'#ifndef BOOT_DITHER_SCALE\n#define BOOT_DITHER_SCALE {a.dscale}   // dither dot size in output pixels, 1..16 (override with -DBOOT_DITHER_SCALE=N)\n#endif\n\n')
        h.write('static const uint32_t BOOT_ALPHA_OFFSETS[BOOT_FRAME_COUNT + 1] PROGMEM = {\n')
        for j in range(0, len(offs), 12):
            h.write('  ' + ','.join(str(v) for v in offs[j:j + 12]) + ',\n')
        h.write('};\n\n')
        h.write(f'static const uint8_t BOOT_ALPHA_DATA[{o}] PROGMEM = {{\n')
        for i, f in enumerate(frames):
            h.write(f'  // {os.path.basename(files[i])}\n')
            for j in range(0, len(f), 16):
                h.write('  ' + ','.join(f'0x{b:02X}' for b in f[j:j + 16]) + ',\n')
        h.write('};\n')

    raw = len(frames) * a.size // 8 * a.size
    print(f'{len(frames)} frames, {a.size}x{a.size}, alpha4 RLE: {o} B total ({o // len(frames)} B/frame avg) '
          f'vs {raw} B as 1 bpp -> {a.out}')


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('inputs', nargs='+', help='PNG files and/or directories (sorted naturally)')
    ap.add_argument('-o', '--out', default='boot_frames.h')
    ap.add_argument('--size', type=int, default=0, help='frame side in px, multiple of 8 (default: size of the first PNG)')
    ap.add_argument('--fps', type=int, default=12)
    ap.add_argument('--threshold', type=int, default=128)
    ap.add_argument('--invert', action='store_true')
    ap.add_argument('--dither', type=int, default=4,
                    help='alpha4 only: Bayer matrix size used by the firmware, a power of two 2..256 (written to the header as BOOT_DITHER_SIZE)')
    ap.add_argument('--dither-scale', type=int, default=1, dest='dscale',
                    help='alpha4 only: size of one dither dot in output pixels, 1..16 (written as BOOT_DITHER_SCALE)')
    ap.add_argument('--format', choices=['bits', 'alpha4'], default='bits',
                    help='bits = 1 bpp (default); alpha4 = 4-bit darkness, RLE, dithered by the firmware')
    ap.add_argument('--preview', action='store_true', help='print frame 0 as ASCII art')
    a = ap.parse_args()

    files = collect(a.inputs)
    if not files:
        sys.exit('no PNG files found')
    if not a.size:
        a.size = Image.open(files[0]).size[0]
    if a.size % 8:
        sys.exit(f'frame size {a.size} is not a multiple of 8 (use --size)')

    if a.format == 'alpha4':
        if not (2 <= a.dither <= 256 and a.dither & (a.dither - 1) == 0):
            sys.exit('--dither must be a power of two between 2 and 256')
        if not 1 <= a.dscale <= 16:
            sys.exit('--dither-scale must be between 1 and 16')
        write_alpha4(a, files)
        return

    frames = [pack(to_bits(f, a.size, a.threshold, a.invert)) for f in files]
    fb = a.size // 8 * a.size
    ones = sum(bin(b).count('1') for f in frames for b in f) / (8 * fb * len(frames))
    if ones > 0.97 or ones < 0.003:
        print(f'warning: {ones:.0%} of pixels are ON - the frames are probably all-black or all-white; check --threshold / --invert', file=sys.stderr)

    if a.preview:
        for y in range(a.size):
            line = ''
            for x in range(a.size):
                line += '#' if frames[0][y * (a.size // 8) + x // 8] & (0x80 >> (x % 8)) else '.'
            print(line)

    with open(a.out, 'w') as h:
        h.write('// Generated by png2frames.py - do not edit.\n')
        h.write('// 1 bpp, row-major, MSB first. 1 = black, 0 = white.\n')
        h.write('#pragma once\n#include <stdint.h>\n#include <pgmspace.h>\n\n')
        h.write(f'#define BOOT_FRAME_W     {a.size}\n#define BOOT_FRAME_H     {a.size}\n')
        h.write(f'#define BOOT_FRAME_COUNT {len(frames)}\n#define BOOT_FRAME_FPS   {a.fps}\n\n')
        h.write(f'static const uint8_t BOOT_FRAMES[BOOT_FRAME_COUNT][{fb}] PROGMEM = {{\n')
        for i, f in enumerate(frames):
            h.write(f'  {{ // {os.path.basename(files[i])}\n')
            for j in range(0, len(f), 16):
                h.write('    ' + ','.join(f'0x{b:02X}' for b in f[j:j + 16]) + ',\n')
            h.write('  },\n')
        h.write('};\n')

    print(f'{len(frames)} frames, {a.size}x{a.size}, {fb} B each, {len(frames) * fb} B total -> {a.out}')


if __name__ == '__main__':
    main()